export function Icon({ name, size = 20, stroke, className = '', ...props }) {
  return (
    <RafeeqIcon
      name={legacyNames[name] || name}
      size={size}
      weight={stroke && stroke <= 1.5 ? 'light' : 'regular'}
      className={className}
      {...props}
    />
  )
}

export function AppIcon({ app, size = 48, className = '' }) {
  return (
    <span
      className={`ros-aicon ${className}`}
      style={{ width: size, height: size, borderRadius: Math.round(size * 0.3), background: app.grad }}
      aria-hidden="true"
    >
      <Icon name={app.icon} size={Math.round(size * 0.54)} />
    </span>
  )
}
