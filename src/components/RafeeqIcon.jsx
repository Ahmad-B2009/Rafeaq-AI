export function RafeeqIcon({
  name,
  size = 20,
  weight = 'regular',
  className = '',
  ...props
}) {
  const IconComponent = icons[name]
  if (!IconComponent) {
    throw new Error(`Unknown Rafeeq icon: "${name}"`)
  }
  return (
    <IconComponent
      size={size}
      weight={weight}
      className={className}
      aria-hidden="true"
      focusable="false"
      {...props}
    />
  )
}

